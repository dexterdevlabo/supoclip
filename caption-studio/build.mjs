#!/usr/bin/env node
// Bundles the studio into one runnable file: caption-studio.mjs
// Run this after changing anything in lib/ or public/.

import fsp from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(dir, 'caption-studio.mjs');

const ASSET_FILES = {
  'index.html': 'public/index.html',
  'style.css': 'public/style.css',
  'app.js': 'public/app.js',
  'lib/ass.mjs': 'lib/ass.mjs',
};
const TYPES = {
  'index.html': 'text/html; charset=utf-8',
  'style.css': 'text/css; charset=utf-8',
  'app.js': 'text/javascript; charset=utf-8',
  'lib/ass.mjs': 'text/javascript; charset=utf-8',
};

const assets = {};
for (const [served, src] of Object.entries(ASSET_FILES)) {
  assets[served] = { body: await fsp.readFile(path.join(dir, src), 'utf8'), type: TYPES[served] };
}

let server = await fsp.readFile(path.join(dir, 'server.mjs'), 'utf8');

const cut = (text, name, replacement) => {
  const re = new RegExp(`// <<BUNDLE:${name}>>[\\s\\S]*?// <</BUNDLE:${name}>>`);
  if (!re.test(text)) throw new Error(`marker ${name} not found in server.mjs`);
  return text.replace(re, replacement);
};

// The browser is served lib/ass.mjs as text; the server imports that very same
// text as a module, so the bundle holds exactly one copy of the engine.
server = cut(server, 'ASS_IMPORT', [
  "const { buildAss, buildSrt, buildVtt, TRANSITIONS } = await import(",
  "  'data:text/javascript;charset=utf-8;base64,' +",
  "    Buffer.from(ASSETS['lib/ass.mjs'].body, 'utf8').toString('base64')",
  ');',
].join('\n'));

server = cut(server, 'ASSETS', [
  'async function readAsset(rel) {',
  '  return ASSETS[rel] || null;',
  '}',
].join('\n'));

// Drop the original shebang/entry line; the bundle supplies its own header.
server = server.replace(/^#!.*\n/, '');

const banner = [
  '#!/usr/bin/env node',
  '// Caption Studio - a single-file local captioning studio.',
  '//',
  '//   node caption-studio.mjs        # then open http://127.0.0.1:4321',
  '//',
  '// Needs Node 20+ and ffmpeg on PATH. No npm install, no other files.',
  '// Generated by build.mjs from lib/ and public/ - edit those, not this.',
  '',
  `const ASSETS = ${JSON.stringify(assets, null, 0)};`,
  '',
].join('\n');

await fsp.writeFile(OUT, banner + server, 'utf8');
await fsp.chmod(OUT, 0o755);
const { size } = await fsp.stat(OUT);
console.log(`built ${path.relative(process.cwd(), OUT)}  (${(size / 1024).toFixed(0)} KB)`);
